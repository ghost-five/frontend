import { launch, newTab } from '../cdp.mjs';
const wait = ms => new Promise(r => setTimeout(r, ms));
const { proc, port } = await launch(9296);
const t1 = await newTab(port), t2 = await newTab(port);
const say = (n, v) => console.log('·', n, '→', v);
const tab = (t,n) => t.eval(`[...document.querySelectorAll('.tab')].find(b=>b.textContent.includes('${n}')).click()`);
await t1.theme('dark'); await t1.size(1440,950); await t2.size(1280,900);
await t1.goto('http://localhost:8778/'); await t1.eval("localStorage.clear()"); await t1.eval("localStorage.setItem('ghost5-settings', JSON.stringify({hold:0}))");
await t1.goto('http://localhost:8778/?as=1'); await wait(1200);
await t2.goto('http://localhost:8778/?as=2'); await wait(1200);
await tab(t1,'По сети'); await wait(500);
await t1.eval("document.getElementById('linkGame').click()"); await wait(1500);
const code = await t1.eval("document.getElementById('gbCode').textContent");
await tab(t2,'По сети'); await wait(600);
await t2.eval(`document.getElementById('joinCode').value='${code}'`);
await t2.eval("document.getElementById('joinForm').dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}))"); await wait(2500);
say('рейтинг в карточках', await t1.eval("[...document.querySelectorAll('.pcard .elo')].map(e=>e.textContent).join(' / ')"));
// второй сдаётся → рейтинг расходится, первый становится первым в таблице
await t2.eval("document.getElementById('resignOnline').click()"); await wait(300);
await t2.eval("document.getElementById('resignOnline').click()"); await wait(3500);
await t1.eval("document.querySelector('[data-act=see-board]') && document.querySelector('[data-act=see-board]').click()"); await wait(400);
await tab(t1,'Лидеры'); await wait(1200);
await tab(t1,'По сети'); await wait(1500);
say('рейтинг после партии', await t1.eval("[...document.querySelectorAll('.pcard .elo')].map(e=>e.textContent).join(' / ')"));
say('медали', await t1.eval("[...document.querySelectorAll('.pcard')].map(c=>c.className.replace('pcard ','')).join(' | ')"));
await t1.screenshot('medal.png');
say('раунд лёг в историю', await t1.eval(`(() => {
  const h = (JSON.parse(localStorage.getItem('mockdb') || '{}').history || []);
  return h.length + ' зап.: ' + h.map((r) => r.owner + ' ' + r.code + ' раунд ' + r.game_no + ' ' + r.mode).join(' | ');
})()`));
say('во второй вкладке', await t2.eval("(JSON.parse(localStorage.getItem('mockdb') || '{}').history || []).map(r => r.owner).join(',')"));
const errs = [...(await t1.logs()), ...(await t2.logs())].filter(e => e.method === 'Runtime.exceptionThrown');
console.log('ошибки:', errs.length ? JSON.stringify(errs.map(e=>e.params.exceptionDetails?.exception?.description)).slice(0,300) : 'нет');
proc.kill(); process.exit(0);
