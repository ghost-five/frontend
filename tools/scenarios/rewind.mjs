import { launch, newTab } from '../cdp.mjs';
const wait = ms => new Promise(r => setTimeout(r, ms));
const { proc, port } = await launch(9287);
const t = await newTab(port);
const say = (n, v) => console.log('·', n, '→', v);
await t.theme('dark'); await t.size(1440,950);
await t.goto('http://localhost:8778/'); await t.eval("localStorage.clear()");
await t.goto('http://localhost:8778/?as=1'); await wait(1600);
await t.eval("(() => { const s = JSON.parse(localStorage.getItem('ghost5-settings') || '{}'); s.hold = 0; localStorage.setItem('ghost5-settings', JSON.stringify(s)); })()");
await t.goto('http://localhost:8778/?as=1'); await wait(1400);
const move = async k => { await t.eval(`(() => { const c=[...document.querySelectorAll('.cell.ok.empty')]; c[Math.floor(c.length*${k})].click(); })()`); await wait(150); await t.eval("document.getElementById('confirm').click()"); await wait(900); };
for (const k of [0.2, 0.4, 0.6]) await move(k);
say('ходов сыграно', await t.eval("document.getElementById('round').textContent + ', фишек ' + document.querySelectorAll('.board .stone').length"));
say('перемотка видна', await t.eval("!document.getElementById('rewind').hidden + ' · ' + document.getElementById('rewindAt').textContent"));
const stones = async () => t.eval("document.querySelectorAll('.board .stone').length");
await t.eval("document.getElementById('stepBack').click()"); await wait(400);
say('шаг назад', await t.eval("document.getElementById('rewindAt').textContent") + ', фишек ' + await stones() + ', доска в прошлом: ' + await t.eval("document.getElementById('board').classList.contains('past')"));
await t.eval("document.getElementById('stepBack').click()"); await wait(400);
say('ещё шаг назад', await t.eval("document.getElementById('rewindAt').textContent") + ', фишек ' + await stones());
say('ходить нельзя', await t.eval("document.querySelectorAll('.cell.ok').length === 0"));
await t.screenshot('rewind-dark.png');
await t.eval("document.getElementById('stepLive').click()"); await wait(400);
say('вернулись к текущему', await t.eval("document.getElementById('rewindAt').textContent") + ', фишек ' + await stones() + ', можно ходить: ' + await t.eval("document.querySelectorAll('.cell.ok').length > 0"));
const errs = (await t.logs()).filter(e => e.method === 'Runtime.exceptionThrown');
console.log('ошибки:', errs.length ? JSON.stringify(errs.map(e=>e.params.exceptionDetails?.exception?.description)).slice(0,300) : 'нет');
proc.kill(); process.exit(0);
